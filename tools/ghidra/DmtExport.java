// Export machine-derived evidence and cached C-like pseudocode.
//@category DMT99
import ghidra.app.script.GhidraScript;
import ghidra.app.decompiler.*;
import ghidra.program.model.address.*;
import ghidra.program.model.listing.*;
import ghidra.program.model.symbol.*;
import ghidra.program.model.scalar.Scalar;
import com.google.gson.*;
import java.nio.file.*;
import java.nio.charset.StandardCharsets;
import java.util.*;
import java.security.MessageDigest;

public class DmtExport extends GhidraScript {
    Gson gson = new GsonBuilder().setPrettyPrinting().create();
    Path root;
    String epoch="";
    Set<String> listed=new HashSet<>();
    Map<String,Object> instructionRecord(Instruction i,String owner) throws Exception {
        Map<String,Object> ir=new LinkedHashMap<>();
        ir.put("address",hx(i.getAddress()));ir.put("function",owner);ir.put("length",i.getLength());ir.put("mnemonic",i.getMnemonicString());ir.put("text",i.toString());
        ir.put("flows",Arrays.stream(i.getFlows()).map(a->hx(a)).toList());
        ir.put("fallthrough",i.getFallThrough()==null?null:hx(i.getFallThrough()));
        ir.put("flow_type",i.getFlowType().toString());
        List<Object> refs=new ArrayList<>();
        for(Reference r:i.getReferencesFrom())if(r.getToAddress().isMemoryAddress())refs.add(Map.of("to",hx(r.getToAddress()),"type",r.getReferenceType().toString()));
        ir.put("references",refs);listed.add(hx(i.getAddress()));return ir;
    }
    String hx(Address a) { return String.format("0x%08x", a.getOffset()); }
    void json(String name, Object obj) throws Exception {
        Files.writeString(root.resolve(name), gson.toJson(obj) + "\n");
    }
    String hash(Function f) throws Exception {
        MessageDigest md = MessageDigest.getInstance("SHA-256");
        AddressRangeIterator it = f.getBody().getAddressRanges();
        while (it.hasNext()) {
            AddressRange r = it.next();
            byte[] b = new byte[(int)r.getLength()];
            currentProgram.getMemory().getBytes(r.getMinAddress(), b); md.update(b);
        }
        md.update(f.getPrototypeString(true,true).getBytes(StandardCharsets.UTF_8));
        md.update(currentProgram.getLanguageID().toString().getBytes(StandardCharsets.UTF_8));
        md.update(epoch.getBytes(StandardCharsets.UTF_8));
        return HexFormat.of().formatHex(md.digest());
    }
    void applyNames() throws Exception {
        Path p = root.resolve("analysis/semantic_names.tsv");
        if (!Files.exists(p)) return;
        for (String line : Files.readAllLines(p)) {
            if (line.isBlank() || line.startsWith("#")) continue;
            String[] x = line.split("\t");
            Address a = toAddr(Long.parseLong(x[0].replace("0x",""),16));
            Function f = getFunctionAt(a);
            if (f == null && getInstructionAt(a) != null) f = createFunction(a,x[1]);
            if (f != null) { f.setName(x[1], SourceType.USER_DEFINED); if(x.length > 2) f.setComment(x[2]); }
        }
        Path globals = root.resolve("analysis/global_names.tsv");
        if (Files.exists(globals)) for (String line : Files.readAllLines(globals)) {
            if (line.isBlank() || line.startsWith("#")) continue;
            String[] x=line.split("\t");
            createLabel(toAddr(Long.parseLong(x[0].replace("0x",""),16)), x[1], true);
        }
    }
    public void run() throws Exception {
        root = Paths.get(getScriptArgs()[0]);
        applyNames();
        for(String path:List.of("analysis/semantic_names.tsv","analysis/global_names.tsv","analysis/function_signatures.tsv","analysis/recovered_types.h","tools/ghidra_wch/data/languages/riscv32.cspec","tools/ghidra/DmtRecover.java","tools/ghidra/DmtTypes.java")) {
            Path ep=root.resolve(path);if(Files.exists(ep))epoch+=Files.readString(ep);
        }
        // References generated by analysis are stronger evidence than a linear sweep.
        int added = 0;
        List<Address> targets = new ArrayList<>();
        InstructionIterator instrs = currentProgram.getListing().getInstructions(true);
        while(instrs.hasNext()) {
            Instruction i=instrs.next();
            for(Reference ref:i.getReferencesFrom()) if(ref.getReferenceType().isCall()) targets.add(ref.getToAddress());
        }
        for(Address a:targets) if(a.getOffset()>=0x6600 && a.getOffset()<0x1e800 && getFunctionAt(a)==null && getInstructionAt(a)!=null) {
            if(createFunction(a,null)!=null) added++;
        }
        if(added>0) analyzeChanges(currentProgram);
        DecompInterface decomp = new DecompInterface();
        DecompileOptions options = new DecompileOptions();
        options.grabFromProgram(currentProgram);
        decomp.setOptions(options); decomp.openProgram(currentProgram);
        List<Object> functions = new ArrayList<>(), edges = new ArrayList<>(), instructions = new ArrayList<>();
        Map<String,Object> hashes = new TreeMap<>();
        int success=0, failures=0;
        try(java.io.BufferedWriter out=Files.newBufferedWriter(root.resolve("disassembly/full_disassembly.asm"))) {
            out.write("; Ghidra listing: RV32 + compressed + Xwchc, soft-float ABI, image base 0x6400. Data is not disassembled.\n");
            FunctionIterator fs = currentProgram.getFunctionManager().getFunctions(true);
            while(fs.hasNext() && !monitor.isCancelled()) {
                Function f=fs.next(); Address entry=f.getEntryPoint();
                if(entry.getOffset()<0x6400 || entry.getOffset()>=0x271d0) continue;
                Map<String,Object> rec=new LinkedHashMap<>();
                rec.put("address",hx(entry)); rec.put("name",f.getName());
                rec.put("size",f.getBody().getNumAddresses());
                List<Object> ranges=new ArrayList<>();
                for(AddressRange r:f.getBody().getAddressRanges()) ranges.add(List.of(hx(r.getMinAddress()),hx(r.getMaxAddress())));
                rec.put("ranges",ranges);
                rec.put("prototype",f.getPrototypeString(true,true));
                rec.put("callers",f.getCallingFunctions(monitor).stream().map(x->hx(x.getEntryPoint())).sorted().toList());
                rec.put("callees",f.getCalledFunctions(monitor).stream().map(x->hx(x.getEntryPoint())).sorted().toList());
                Set<String> refs=new TreeSet<>(), strings=new TreeSet<>(), constants=new TreeSet<>();
                out.write("\n"+hx(entry)+" <"+f.getName()+">:\n");
                InstructionIterator fi=currentProgram.getListing().getInstructions(f.getBody(),true);
                while(fi.hasNext()) {
                    Instruction i=fi.next();
                    out.write(hx(i.getAddress())+"  "+HexFormat.of().formatHex(i.getBytes())+"  "+i.toString()+"\n");
                    Map<String,Object> ir=instructionRecord(i,hx(entry));
                    List<Object> rr=new ArrayList<>();
                    for(Reference ref:i.getReferencesFrom()) {
                        Address a=ref.getToAddress();
                        if(a.isMemoryAddress()) {
                            refs.add(hx(a));
                            rr.add(Map.of("to",hx(a),"type",ref.getReferenceType().toString()));
                            Data d=getDataAt(a);
                            if(d!=null && d.hasStringValue()) strings.add(String.valueOf(d.getValue()));
                            if(ref.getReferenceType().isCall()) edges.add(Map.of("from",hx(entry),"site",hx(i.getAddress()),"to",hx(a),"type",ref.getReferenceType().toString()));
                        }
                    }
                    ir.put("references",rr); instructions.add(ir);
                    for(int op=0;op<i.getNumOperands();op++) for(Object x:i.getOpObjects(op)) if(x instanceof Scalar) constants.add(String.format("0x%x",((Scalar)x).getUnsignedValue()));
                }
                rec.put("data_references",refs); rec.put("referenced_strings",strings); rec.put("constants",constants);
                rec.put("confidence","machine-discovered; semantic assessment pending");
                String file=String.format("%08x.c",entry.getOffset());
                String fingerprint=hash(f);
                hashes.put(hx(entry),fingerprint);
                Path raw=root.resolve("decompiled/raw/"+file);
                Path stamp=root.resolve(".cache/"+file+".sha256");
                boolean cached=Files.exists(raw) && Files.exists(stamp) && Files.readString(stamp).equals(fingerprint);
                if(cached) {rec.put("decompiled",true); rec.put("cached",true); success++;}
                else {
                    DecompileResults d=decomp.decompileFunction(f,45,monitor);
                    if(d.decompileCompleted() && d.getDecompiledFunction()!=null) {
                        Files.writeString(raw,"/* Original address: "+hx(entry)+"; Ghidra pseudocode, not compilable reconstructed source. */\n"+d.getDecompiledFunction().getC());
                        Files.writeString(stamp,fingerprint);
                        rec.put("decompiled",true); success++;
                    } else {rec.put("decompiled",false);rec.put("decompiler_error",d.getErrorMessage());failures++;}
                }
                rec.put("pseudocode_file","decompiled/raw/"+file);
                functions.add(rec);
                if(functions.size()%100==0) println("Exported "+functions.size()+" functions");
            }
            out.write("\n; Additional decoded/shared instructions outside exclusive Ghidra function bodies\n");
            InstructionIterator remaining=currentProgram.getListing().getInstructions(true);
            while(remaining.hasNext()) {
                Instruction i=remaining.next();long a=i.getAddress().getOffset();
                if(a>=0x6600 && a<0x1e820 && !listed.contains(hx(i.getAddress()))) {
                    out.write(hx(i.getAddress())+"  "+HexFormat.of().formatHex(i.getBytes())+"  "+i.toString()+"\n");
                    instructions.add(instructionRecord(i,null));
                }
            }
        }
        decomp.dispose();
        json("analysis/functions.json",functions); json("analysis/callgraph.json",edges); json("analysis/instructions.json",instructions);
        json("analysis/function_hashes.json",hashes);
        List<Object> blocks=new ArrayList<>();
        for(ghidra.program.model.mem.MemoryBlock b:currentProgram.getMemory().getBlocks())
            blocks.add(Map.of("name",b.getName(),"start",b.getStart().toString(),"size",b.getSize(),"read",b.isRead(),"write",b.isWrite(),"execute",b.isExecute(),"volatile",b.isVolatile()));
        json("analysis/ghidra_memory_blocks.json",blocks);
        List<Object> data=new ArrayList<>();
        DataIterator ds=currentProgram.getListing().getDefinedData(true);
        while(ds.hasNext()) {
            Data d=ds.next();
            if(d.hasStringValue()) data.add(Map.of("address",hx(d.getAddress()),"value",String.valueOf(d.getValue()),"length",d.getLength()));
        }
        json("analysis/ghidra_strings.json",data);
        json("analysis/decompiler_status.json",Map.of("functions",functions.size(),"success",success,"failed",failures,"language",currentProgram.getLanguageID().toString(),"ghidra",getGhidraVersion()));
        println("DMT export: "+functions.size()+" functions, "+success+" decompiled, "+failures+" failed");
    }
}
